def _jsonable(value: Any) -> Any:
    if isinstance(value, tuple):
        return [_jsonable(v) for v in value]
    if isinstance(value, list):
        return [_jsonable(v) for v in value]
    if isinstance(value, dict):
        return {k: _jsonable(v) for k, v in value.items()}
    return value


def resolve_space(space: str | Mapping[str, Any] | PropertySpace) -> PropertySpace:
    """A vector case's ``space``: a registered space's name, or its JSON form."""
    if isinstance(space, PropertySpace):
        return space
    if isinstance(space, str):
        return get_space(space)
    return space_from_json(space)


def state_at(doc: Mapping[str, Any], t: float, *, space: Any) -> dict[str, Any]:
    """The sparse state of compiled document ``doc`` at ``t``, keyed by address."""
    pose = evaluate_timeline(timeline_from_compiled(doc), t, space=resolve_space(space))
    return {
        format_address(target, prop): _jsonable(v) for (target, prop), v in pose.items()
    }


def values_close(expected: Any, actual: Any, *, rel_tol: float = REL_TOL) -> bool:
    """The contract's comparison (see the module docstring).

    >>> values_close(1e9, 1e9 + 0.5), values_close([1, "a"], [1.0, "a"]), values_close(True, 1)
    (True, True, False)
    """
    if isinstance(expected, bool) or isinstance(actual, bool):
        return type(expected) is type(actual) and expected == actual
    if isinstance(expected, (int, float)) and isinstance(actual, (int, float)):
        if math.isnan(expected) or math.isnan(actual):
            return math.isnan(expected) and math.isnan(actual)
        return abs(expected - actual) <= rel_tol * max(1.0, abs(expected), abs(actual))
    if isinstance(expected, list) and isinstance(actual, list):
        return len(expected) == len(actual) and all(
            values_close(e, a, rel_tol=rel_tol) for e, a in zip(expected, actual)
        )
    if isinstance(expected, dict) and isinstance(actual, dict):
        return expected.keys() == actual.keys() and all(
            values_close(expected[k], actual[k], rel_tol=rel_tol) for k in expected
        )
    return expected == actual


#: The cases whose space is the value-typed rule's write-group space are ALSO
#: evaluated with ``space=VALUE_TYPED`` — the rule ``runtime.js`` implements —
#: so both rules are held to the same numbers (the default, ``space=None``, is
#: the declared rule since an#239 item 2).
VALUE_TYPED_CASE_SPACE: str = "stage.node"


def _state_value_typed(doc: Mapping[str, Any], t: float) -> dict[str, Any]:
    pose = evaluate_timeline(timeline_from_compiled(doc), t, space=VALUE_TYPED)
    return {format_address(tg, pr): _jsonable(v) for (tg, pr), v in pose.items()}


def check_vectors(vectors: Mapping[str, Any] | None = None) -> list[str]:
    """Every sample of ``vectors`` (default: the committed file) that ``an.timing``
    does not reproduce, as one line each. Empty means the kernel meets the contract.

    Both evaluation rules are held: every case under its declared space, and every
    ``stage.node`` case also under the value-typed rule (``space=VALUE_TYPED``)."""
    if vectors is None:
        vectors = load_contract_file(VECTORS_FILE)
    problems = []
    for case in vectors["cases"]:
        rules = [
            ("declared", lambda doc, t, sp=case["space"]: state_at(doc, t, space=sp))
        ]
        if case["space"] == VALUE_TYPED_CASE_SPACE:
            rules.append(("value-typed", _state_value_typed))
        for rule, evaluate in rules:
            for sample in case["samples"]:
                got = evaluate(case["document"], sample["t"])
                if not values_close(sample["state"], got):
                    problems.append(
                        f"{case['name']} ({rule}) at t={sample['t']!r}: "
                        f"expected {sample['state']}, got {got}"
                    )
    return problems


