def build_vectors() -> dict[str, Any]:
    out_cases = []
    for case in _vectors.cases():
        samples = [
            {"t": t, "state": state_at(case["document"], t, space=case["space"])}
            for t in case["times"]
        ]
        out_cases.append(
            {
                "name": case["name"],
                "description": case["description"],
                "origin": case["origin"],
                "space": case["space"],
                "document": case["document"],
                "samples": samples,
            }
        )
    return {
        "format": "an.timing.vectors",
        "version": CONTRACT_VERSION,
        "description": (
            "For each case, the sparse state an implementation of the timing kernel "
            "must return at each listed time, for a compiled document "
            "(compiled.schema.json) under a property space (a registered name from "
            "kinds.json, or inline). States are keyed by address (target:property); "
            "an address no clip has started is absent. Numbers agree within "
            f"{REL_TOL} * max(1, |x|, |y|); everything else exactly. 'stage.node' "
            "cases use only the stage's easings and are also what runtime.js "
            "evaluates. Sample times include every clip and keyframe boundary and "
            "every midpoint between them."
        ),
        "tolerance": {"relative": REL_TOL, "floor": 1.0},
        "cases": out_cases,
    }


def build_contract() -> dict[str, Any]:
    """Every contract file's content, by file name, generated from the registries."""
    return {
        EASING_FILE: build_easing(),
        KINDS_FILE: build_kinds(),
        TIMELINE_SCHEMA_FILE: build_timeline_schema(),
        COMPILED_SCHEMA_FILE: build_compiled_schema(),
        VECTORS_FILE: build_vectors(),
    }


def dumps(obj: Any) -> str:
    """The committed text of a contract file (stable, diffable)."""
    return json.dumps(obj, indent=1, ensure_ascii=False, allow_nan=False) + "\n"


def load_contract_file(name: str, *, directory: Path = CONTRACT_DIR) -> Any:
    return json.loads((directory / name).read_text(encoding="utf-8"))


def write_contract(directory: Path = CONTRACT_DIR) -> list[Path]:
    """Regenerate every contract file under ``directory``."""
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, obj in build_contract().items():
        path = directory / name
        path.write_text(dumps(obj), encoding="utf-8")
        written.append(path)
    return written


def contract_drift(directory: Path = CONTRACT_DIR) -> list[str]:
    """How the committed files differ from what the registries generate today.

    Numbers compare with the contract's tolerance, because a transcendental
    function (``exp``, ``sin``, ``pow``) may differ in its last bit across
    platforms' maths libraries; anything else must match exactly.
    """
    drift = []
    for name, built in build_contract().items():
        path = directory / name
        if not path.exists():
            drift.append(f"{name}: missing")
            continue
        committed = json.loads(path.read_text(encoding="utf-8"))
        if not values_close(committed, _jsonable(json.loads(dumps(built)))):
            drift.append(f"{name}: differs from what the registries generate")
        if name == VECTORS_FILE:
            names = lambda doc: {c["name"] for c in doc.get("cases", ())}  # noqa: E731
            removed = sorted(names(committed) - names(built))
            if removed:
                drift.append(f"{name}: cases removed: {removed}")
    return drift


def main(argv: list[str] | None = None) -> int:
    """``python -m an.timing.contract [write|check]``."""
    args = sys.argv[1:] if argv is None else argv
    command = args[0] if args else "check"
    if command == "write":
        for path in write_contract():
            print(f"wrote {path.name}")
        return 0
    if command == "check":
        problems = contract_drift() + check_vectors()
        for line in problems:
            print(line)
        return 1 if problems else 0
    print(f"usage: python -m an.timing.contract [write|check]; got {command!r}")
    return 2


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
