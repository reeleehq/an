#: Where every easing is sampled: a uniform grid, plus points that reach the
#: solvers' fallbacks (near the ends, and around the middle of a curve whose
#: slope vanishes there, e.g. cubic-bezier(1, 0, 0, 1)).
SOLVER_PROBE_U: tuple[float, ...] = (1e-6, 0.4, 0.501, 1 - 1e-6)
SAMPLE_U: tuple[float, ...] = tuple(
    sorted(
        {i / EASING_SAMPLE_STEPS for i in range(EASING_SAMPLE_STEPS + 1)}
        | set(SOLVER_PROBE_U)
    )
)


def _easing_samples(spec: Any) -> list[float]:
    return [apply_easing(spec, u) for u in SAMPLE_U]


#: Parametrised specs the easing file samples, beside the named entries.
PARAMETRIC_EXAMPLES: tuple[Any, ...] = (
    "cubic-bezier(0.25, 0.1, 0.25, 1)",
    "cubic-bezier(0.5, -0.8, 0.5, 1.8)",
    "cubic-bezier(0.3, 1.8, 0.7, -0.8)",
    "steps(4)",
    "steps(4, jump-start)",
    "steps(3, jump-none)",
    "steps(2, jump-both)",
    "steps(2, start)",
    "cubic-bezier(1, 0, 0, 1)",  # Newton stalls mid-curve: the bisection runs
    [0.42, 0.0, 0.58, 1.0],
    [0.5, 2.0, 0.5, 2.0],
    [0.3, 3.0, 0.7, 0.0],
    [1.0, 0.0, 0.0, 1.0],  # the legacy solver's slope guard and clamps
    [0.42, 0.0, 1.0, 1.0],
    [0.0, 0.0, 0.58, 1.0],
)

#: How a CSS-named document's names map onto this registry where the name means
#: something else here. ``ease`` is `an`'s quadratic (ADR 0001 decision 10,
#: amended 2026-10-01); a CSS document's ``ease`` is this spec.
CSS_IMPORT_ALIASES: dict[str, str] = {"ease": "cubic-bezier(0.25, 0.1, 0.25, 1)"}


def build_easing() -> dict[str, Any]:
    return {
        "format": "an.timing.easing",
        "version": CONTRACT_VERSION,
        "description": (
            "Every named easing, the solver that computes it, and its value at "
            "u in 'sample_u'. Hyphenated CSS names are the exact CSS "
            "curves; an's underscore names (and 'ease') are an's own polynomial "
            "curves, so a CSS document's 'ease' must be read through "
            "'css_import_aliases'; Manim's rate functions keep Manim's names. A bare 4-number "
            "list is a cubic Bezier solved by 'an-bezier-newton-8'; the string "
            "'cubic-bezier(...)' is solved by 'css-bezier-newton-bisection'."
        ),
        "families": list(EASING_FAMILIES),
        "solvers": solvers(owner=CORE_OWNER),
        "css_hyphenated_curves": {
            k: list(v) for k, v in CSS_BEZIERS.items() if k not in CSS_IMPORT_ALIASES
        },
        "css_import_aliases": dict(CSS_IMPORT_ALIASES),
        "step_positions": list(STEP_POSITIONS),
        "sample_u": list(SAMPLE_U),
        "entries": [
            {**e.to_json(), "samples": _easing_samples(e.name)}
            for e in easing_entries(owner=CORE_OWNER)
        ],
        "parametric": [
            {
                "spec": spec,
                "solver": (
                    "an-bezier-newton-8"
                    if isinstance(spec, list)
                    else "css-steps"
                    if spec.startswith("steps")
                    else "css-bezier-newton-bisection"
                ),
                "samples": _easing_samples(spec),
            }
            for spec in PARAMETRIC_EXAMPLES
        ],
    }


def _kind_samples(kind: Any, a: Any, b: Any, us: tuple[float, ...]) -> list[dict]:
    return [
        {
            "a": a,
            "b": b,
            "u": u,
            "value": _jsonable(kind.interpolate(a, b, u, Segment(u, 0.0, 1.0))),
        }
        for u in us
    ]


def _discrete_samples(
    kind: DiscreteKind, start: float, end: float, ts: list[float]
) -> list[dict]:
    return [
        {
            "a": "A",
            "b": "B",
            "segment": [start, end],
            "t": t,
            "value": kind.interpolate("A", "B", 0.0, Segment(t, start, end)),
        }
        for t in ts
    ]


def build_kinds() -> dict[str, Any]:
    us = (0.0, 0.25, 0.5, 0.75, 1.0, 1.25)
    quarter = [0.0, 0.25, 0.5, 0.75, math.nextafter(1.0, 0.0)]
    examples = [
        (NumberKind(), -2.0, 3.0, us),
        (NumberKind(space="log"), 1.0, 4.0, us),
        (AngleKind(), 350.0, 10.0, us),
        (AngleKind(), 10.0, 350.0, us[:5]),
        (AngleKind(unit="rad"), 0.1, 6.1, us[:5]),
        (AngleKind(wrap=False), 0.0, 720.0, us[:5]),
        (VectorKind(), [0.0, 0.0, 0.0], [1.0, -2.0, 4.0], us[:5]),
        (QuaternionKind(), [0.0, 0.0, 0.0, 1.0], [-0.5, -0.5, -0.5, -0.5], us[:5]),
        (ColorKind(), "#ff0000", "#00ff00", us[:5]),
        (ColorKind(), [0.2, 0.4, 0.6], [1.0, 0.5, 0.0, 0.5], us[:5]),
        (ColorKind(space="srgb"), "#ff0000", "#0000ff80", us[:5]),
        (
            OrbitKind(),
            {
                "azimuth": 340.0,
                "elevation": 10.0,
                "distance": 2.0,
                "target": [0.0, 0.0, 0.0],
                "projection": "perspective",
            },
            {
                "azimuth": 30.0,
                "elevation": 60.0,
                "distance": 8.0,
                "target": [1.0, 2.0, 3.0],
                "projection": "orthographic",
            },
            us[:5],
        ),
    ]
    by_kind: dict[str, list[dict]] = {}
    for kind, a, b, u_list in examples:
        by_kind.setdefault(kind.name, []).append(
            {"spec": kind.to_spec(), "samples": _kind_samples(kind, a, b, u_list)}
        )
    by_kind["discrete"] = [
        {
            "spec": DiscreteKind().to_spec(),
            "samples": _discrete_samples(DiscreteKind(), 0.0, 1.0, quarter),
        },
        {
            "spec": DiscreteKind(switch_at=0.25).to_spec(),
            "samples": _discrete_samples(
                DiscreteKind(switch_at=0.25), 2.0, 4.0, [2.0, 2.49, 2.5, 3.0]
            ),
        },
        {
            "spec": DiscreteKind(switch_at=1).to_spec(),
            "note": "switch_at == 1 is t >= b.time with no arithmetic: at the float below "
            "b.time, (t - a.time) / span rounds to 1.0 and the value is still 'A'",
            "samples": _discrete_samples(
                DiscreteKind(switch_at=1),
                _vectors.BOUNDARY_A,
                _vectors.BOUNDARY_B,
                [
                    _vectors.BOUNDARY_A,
                    5.0,
                    math.nextafter(_vectors.BOUNDARY_B, 0.0),
                    _vectors.BOUNDARY_B,
                ],
            ),
        },
    ]
    kinds = []
    for name in by_kind:
        factory = kind_from_spec(name)
        kinds.append(
            {
                "kind": name,
                "description": (type(factory).__doc__ or "").strip().split("\n\n")[0],
                "params": {f.name: getattr(factory, f.name) for f in fields(factory)},
                "examples": by_kind[name],
            }
        )
    return {
        "format": "an.timing.kinds",
        "version": CONTRACT_VERSION,
        "description": (
            "Each field kind's parameters (with defaults) and sample interpolations. "
            "'u' is the eased progress handed to the kind; a discrete kind ignores it "
            "and switches on time t in 'segment' = [a.time, b.time). An undeclared "
            "property is {'kind': 'discrete'} (switch_at 0.5)."
        ),
        "kinds": kinds,
        "spaces": [get_space(n).to_json() for n in space_names(owner=CORE_OWNER)],
    }


_EASING_SPEC_SCHEMA: dict[str, Any] = {
    "description": (
        "null (linear), a name or parametrised spec from easing.json, or a 4-number "
        "cubic-Bezier control list solved by an's legacy solver. The schema does "
        "NOT check names (the registry is open); an evaluator refuses an unknown one"
    ),
    "anyOf": [
        {"type": "null"},
        {"type": "string", "minLength": 1},
        {"type": "array", "items": {"type": "number"}, "minItems": 4, "maxItems": 4},
    ],
}

#: The address grammar as a regular expression (the parser is ``an.timing.address``).
ADDRESS_PATTERN: str = r"^[^:/@\s](?:[^:/@]*[^:/@\s])?(?:/[^:/@\s](?:[^:/@]*[^:/@\s])?)*:[^:/@.\s](?:[^:/@.]*[^:/@.\s])?(?:\.[^:/@.\s](?:[^:/@.]*[^:/@.\s])?)*(?:@[^:/@\s](?:[^:/@]*[^:/@\s])?)?$"


